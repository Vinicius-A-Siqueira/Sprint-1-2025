    TYPE t_tab_manutencao IS TABLE OF t_manutencao INDEX BY PLS_INTEGER;
    v_dados t_tab_manutencao;
    
    -- Variáveis de controle
    v_index NUMBER := 1;
    v_filial_anterior VARCHAR2(100) := '';
    v_subtotal_filial NUMBER(10,2) := 0;
    v_total_geral NUMBER(10,2) := 0;
    v_count_registros NUMBER := 0;
    
    -- Cursor para dados ordenados
    CURSOR c_dados IS
        SELECT f.nome as nome_filial,
               u.cargo,
               m.custo
        FROM manutencao m
        JOIN moto mo ON m.moto_id_moto = mo.id_moto
        JOIN patio p ON (mo.patio_id_patio = p.id_patio AND mo.patio_filial_id_filial = p.filial_id_filial)
        JOIN filial f ON p.filial_id_filial = f.id_filial
        JOIN usuario u ON (m.id_manutencao = u.manutencao_id_manutencao AND m.moto_id_moto = u.manutencao_moto_id_moto)
        ORDER BY f.nome, u.cargo;
    
    -- Exceções personalizadas  
    DADOS_INSUFICIENTES EXCEPTION;
    ERRO_CALCULO EXCEPTION;
    CURSOR_ERRO EXCEPTION;
    
BEGIN
    DBMS_OUTPUT.PUT_LINE('=== RELATÓRIO DE CUSTOS DE MANUTENÇÃO ===');
    DBMS_OUTPUT.PUT_LINE('Data: ' || TO_CHAR(SYSDATE, 'DD/MM/YYYY HH24:MI:SS'));
    DBMS_OUTPUT.PUT_LINE('');
    DBMS_OUTPUT.PUT_LINE(RPAD('FILIAL', 25) || RPAD('CARGO', 20) || RPAD('CUSTO', 15));
    DBMS_OUTPUT.PUT_LINE(RPAD('-', 25, '-') || RPAD('-', 20, '-') || RPAD('-', 15, '-'));
    
    -- Carregamento dos dados no array
    FOR rec IN c_dados LOOP
        v_dados(v_index).nome_filial := rec.nome_filial;
        v_dados(v_index).cargo_usuario := rec.cargo;
        v_dados(v_index).custo := rec.custo;
        v_index := v_index + 1;
        v_count_registros := v_count_registros + 1;
    END LOOP;
    
    -- Verificação se há dados suficientes
    IF v_count_registros < 5 THEN
        RAISE DADOS_INSUFICIENTES;
    END IF;
    
    -- Processamento manual dos totais
    FOR i IN 1..v_dados.COUNT LOOP
        -- Quebra por filial (subtotal)
        IF v_filial_anterior != v_dados(i).nome_filial AND v_filial_anterior != '' THEN
            -- Exibe subtotal da filial anterior
            DBMS_OUTPUT.PUT_LINE(RPAD(' ', 25) || RPAD('SUBTOTAL', 20) || RPAD(TO_CHAR(v_subtotal_filial, '999,999.99'), 15));
            DBMS_OUTPUT.PUT_LINE('');
            v_subtotal_filial := 0;
        END IF;
        
        -- Exibe linha de detalhe
        DBMS_OUTPUT.PUT_LINE(RPAD(v_dados(i).nome_filial, 25) || 
                           RPAD(v_dados(i).cargo_usuario, 20) || 
                           RPAD(TO_CHAR(v_dados(i).custo, '999,999.99'), 15));
        
        -- Acumula totais
        v_subtotal_filial := v_subtotal_filial + v_dados(i).custo;
        v_total_geral := v_total_geral + v_dados(i).custo;
        
        -- Atualiza filial anterior
        v_filial_anterior := v_dados(i).nome_filial;
    END LOOP;
    
    -- Subtotal da última filial
    IF v_subtotal_filial > 0 THEN
        DBMS_OUTPUT.PUT_LINE(RPAD(' ', 25) || RPAD('SUBTOTAL', 20) || RPAD(TO_CHAR(v_subtotal_filial, '999,999.99'), 15));
        DBMS_OUTPUT.PUT_LINE('');
    END IF;
    
    -- Total geral
    DBMS_OUTPUT.PUT_LINE(RPAD('-', 60, '-'));
    DBMS_OUTPUT.PUT_LINE(RPAD(' ', 25) || RPAD('TOTAL GERAL', 20) || RPAD(TO_CHAR(v_total_geral, '999,999.99'), 15));
    
    DBMS_OUTPUT.PUT_LINE('');
    DBMS_OUTPUT.PUT_LINE('Registros processados: ' || v_count_registros);
    DBMS_OUTPUT.PUT_LINE('=== FIM DO RELATÓRIO ===');

EXCEPTION
    WHEN DADOS_INSUFICIENTES THEN
        DBMS_OUTPUT.PUT_LINE('ERRO: Dados insuficientes. Mínimo de 5 registros requeridos.');
        DBMS_OUTPUT.PUT_LINE('Registros encontrados: ' || v_count_registros);
    WHEN ERRO_CALCULO THEN
        DBMS_OUTPUT.PUT_LINE('ERRO: Falha nos cálculos de totalização');
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('ERRO INESPERADO: ' || SQLERRM);
        DBMS_OUTPUT.PUT_LINE('Posição: ' || v_index);
END relatorio_custos_manutencao;
