-- FUNÇÃO 1: CONVERSÃO MANUAL PARA JSON
-- =============================================================================

CREATE OR REPLACE FUNCTION converter_para_json(
    p_tabela VARCHAR2,
    p_condicao VARCHAR2 DEFAULT NULL
) RETURN CLOB
IS
    v_json CLOB := '';
    v_first BOOLEAN := TRUE;
    v_cursor SYS_REFCURSOR;
    v_sql VARCHAR2(4000);
    
    -- Variáveis para diferentes tipos de consulta
    v_id_moto NUMBER;
    v_placa VARCHAR2(10);
    v_nome_filial VARCHAR2(100);
    v_nome_patio VARCHAR2(100);
    v_status_desc VARCHAR2(50);
    v_ano_fabricacao DATE;
    
    -- Exceções personalizadas
    TABELA_INEXISTENTE EXCEPTION;
    CONSULTA_INVALIDA EXCEPTION;
    DADOS_INSUFICIENTES EXCEPTION;
    
BEGIN
    -- Validação da tabela
    IF p_tabela IS NULL OR LENGTH(TRIM(p_tabela)) = 0 THEN
        RAISE TABELA_INEXISTENTE;
    END IF;
    
    -- Início do JSON
    v_json := '[';
    
    -- Query específica para moto com JOIN
    IF UPPER(p_tabela) = 'MOTO_COMPLETA' THEN
        v_sql := 'SELECT m.id_moto, m.placa, f.nome as nome_filial, p.nome as nome_patio, s.descricao as status_desc, m.ano_fabricacao
                  FROM moto m
                  JOIN patio p ON (m.patio_id_patio = p.id_patio AND m.patio_filial_id_filial = p.filial_id_filial)
                  JOIN filial f ON p.filial_id_filial = f.id_filial
                  JOIN statusmoto s ON m.statusmoto_id_status = s.id_status';
        
        IF p_condicao IS NOT NULL THEN
            v_sql := v_sql || ' WHERE ' || p_condicao;
        END IF;
        
        OPEN v_cursor FOR v_sql;
        
        LOOP
            FETCH v_cursor INTO v_id_moto, v_placa, v_nome_filial, v_nome_patio, v_status_desc, v_ano_fabricacao;
            EXIT WHEN v_cursor%NOTFOUND;
            
            IF NOT v_first THEN
                v_json := v_json || ',';
            END IF;
            
            -- Montagem manual do JSON
            v_json := v_json || '{' ||
                     '"id_moto":' || v_id_moto || ',' ||
                     '"placa":"' || v_placa || '",' ||
                     '"filial":"' || v_nome_filial || '",' ||
                     '"patio":"' || v_nome_patio || '",' ||
                     '"status":"' || v_status_desc || '",' ||
                     '"ano":"' || TO_CHAR(v_ano_fabricacao, 'YYYY') || '"' ||
                     '}';
            
            v_first := FALSE;
        END LOOP;
        
        CLOSE v_cursor;
        
    ELSE
        RAISE CONSULTA_INVALIDA;
    END IF;
    
    -- Verifica se encontrou dados
    IF v_first THEN
        RAISE DADOS_INSUFICIENTES;
    END IF;
    
    -- Finalização do JSON
    v_json := v_json || ']';
    
    RETURN v_json;

EXCEPTION
    WHEN TABELA_INEXISTENTE THEN
        RETURN '{"erro": "Tabela não especificada ou inválida"}';
    WHEN CONSULTA_INVALIDA THEN
        RETURN '{"erro": "Tipo de consulta não suportado"}';
    WHEN DADOS_INSUFICIENTES THEN
        RETURN '{"erro": "Nenhum dado encontrado para os critérios especificados"}';
    WHEN OTHERS THEN
        RETURN '{"erro": "Erro interno: ' || SQLERRM || '"}';
END converter_para_json;
/

-- =============================================================================
-- FUNÇÃO 2: VALIDAÇÃO DE PLACA DE MOTO
-- =============================================================================

CREATE OR REPLACE FUNCTION validar_placa_moto(
    p_placa VARCHAR2
) RETURN VARCHAR2
IS
    v_resultado VARCHAR2(100);
    v_count NUMBER;
    v_formato_valido NUMBER := 0;
    
    -- Exceções personalizadas
    PLACA_NULA EXCEPTION;
    PLACA_DUPLICADA EXCEPTION;
    FORMATO_INVALIDO EXCEPTION;
    
BEGIN
    -- Validação: placa não pode ser nula
    IF p_placa IS NULL OR LENGTH(TRIM(p_placa)) = 0 THEN
        RAISE PLACA_NULA;
    END IF;
    
    -- Validação do formato da placa (ABC-1234)
    SELECT CASE 
        WHEN REGEXP_LIKE(UPPER(TRIM(p_placa)), '^[A-Z]{3}-[0-9]{4}$') THEN 1
        ELSE 0
    END INTO v_formato_valido FROM DUAL;
    
    IF v_formato_valido = 0 THEN
        RAISE FORMATO_INVALIDO;
    END IF;
    
    -- Verificação de duplicação
    SELECT COUNT(*) INTO v_count 
    FROM moto 
    WHERE UPPER(placa) = UPPER(TRIM(p_placa));
    
    IF v_count > 0 THEN
        RAISE PLACA_DUPLICADA;
    END IF;
    
    -- Se passou em todas as validações
    v_resultado := 'VÁLIDA: Placa ' || UPPER(TRIM(p_placa)) || ' aprovada para cadastro';
    
    RETURN v_resultado;

EXCEPTION
    WHEN PLACA_NULA THEN
        RETURN 'INVÁLIDA: Placa não pode ser nula ou vazia';
    WHEN FORMATO_INVALIDO THEN
        RETURN 'INVÁLIDA: Formato deve ser ABC-1234 (3 letras, hífen, 4 números)';
    WHEN PLACA_DUPLICADA THEN
        RETURN 'INVÁLIDA: Placa já cadastrada no sistema';
    WHEN OTHERS THEN
        RETURN 'ERRO: ' || SQLERRM;
END validar_placa_moto;
/

-- =============================================================================
-- PROCEDIMENTO 1: EXIBIÇÃO DE DADOS COM JOIN EM FORMATO JSON
-- =============================================================================

CREATE OR REPLACE PROCEDURE exibir_motos_json(
    p_filtro_status VARCHAR2 DEFAULT NULL
)
IS
    v_json_result CLOB;
    v_count NUMBER := 0;
    
    -- Exceções personalizadas
    STATUS_INEXISTENTE EXCEPTION;
    ERRO_CONVERSAO EXCEPTION;
    NENHUM_DADO EXCEPTION;
    
BEGIN
    DBMS_OUTPUT.PUT_LINE('=== RELATÓRIO DE MOTOS EM FORMATO JSON ===');
    DBMS_OUTPUT.PUT_LINE('Data/Hora: ' || TO_CHAR(SYSDATE, 'DD/MM/YYYY HH24:MI:SS'));
    DBMS_OUTPUT.PUT_LINE('');
    
    -- Validação do filtro de status se fornecido
    IF p_filtro_status IS NOT NULL THEN
        SELECT COUNT(*) INTO v_count 
        FROM statusmoto 
        WHERE UPPER(descricao) = UPPER(p_filtro_status);
        
        IF v_count = 0 THEN
            RAISE STATUS_INEXISTENTE;
        END IF;
    END IF;
    
    -- Chamada da função de conversão JSON
    IF p_filtro_status IS NOT NULL THEN
        v_json_result := converter_para_json('MOTO_COMPLETA', 
            'UPPER(s.descricao) = UPPER(''' || p_filtro_status || ''')');
    ELSE
        v_json_result := converter_para_json('MOTO_COMPLETA');
    END IF;
    
    -- Verificação se houve erro na conversão
    IF v_json_result LIKE '%"erro"%' THEN
        RAISE ERRO_CONVERSAO;
    END IF;
    
    -- Verificação se há dados
    IF v_json_result = '[]' THEN
        RAISE NENHUM_DADO;
    END IF;
    
    -- Exibição do resultado JSON
    DBMS_OUTPUT.PUT_LINE('JSON Result:');
    DBMS_OUTPUT.PUT_LINE(v_json_result);
    
    DBMS_OUTPUT.PUT_LINE('');
    DBMS_OUTPUT.PUT_LINE('=== FIM DO RELATÓRIO ===');

EXCEPTION
    WHEN STATUS_INEXISTENTE THEN
        DBMS_OUTPUT.PUT_LINE('ERRO: Status "' || p_filtro_status || '" não encontrado no sistema');
    WHEN ERRO_CONVERSAO THEN
        DBMS_OUTPUT.PUT_LINE('ERRO: Falha na conversão para JSON: ' || v_json_result);
    WHEN NENHUM_DADO THEN
        DBMS_OUTPUT.PUT_LINE('AVISO: Nenhum dado encontrado para os critérios especificados');
    WHEN OTHERS THEN
        DBMS_OUTPUT.PUT_LINE('ERRO INESPERADO: ' || SQLERRM);
        DBMS_OUTPUT.PUT_LINE('Código do erro: ' || SQLCODE);
END exibir_motos_json;
/

