ALTER TABLE moto ADD FOREIGN KEY (sensor_iot_id_sensor) REFERENCES sensor_iot(id_sensor);

-- Tabela de relacionamento Sensor_Leitura
CREATE TABLE sensor_leitura (
    sensor_iot_id_sensor NUMBER(9),
    leitura_id_leitura NUMBER(9),
    valor NUMBER(10,2) NOT NULL, -- Valor da leitura para análise
    PRIMARY KEY (sensor_iot_id_sensor, leitura_id_leitura),
    FOREIGN KEY (sensor_iot_id_sensor) REFERENCES sensor_iot(id_sensor),
    FOREIGN KEY (leitura_id_leitura) REFERENCES leitura(id_leitura)
);

-- Tabela Deteccao
CREATE TABLE deteccao (
    id_deteccao NUMBER(9),
    moto_id_moto NUMBER(9),
    camera_id_camera NUMBER(9),
    camera_id_patio NUMBER(9),
    camera_id_filial NUMBER(9),
    data_hora TIMESTAMP(0) NOT NULL,
    coordenadas VARCHAR2(100) NOT NULL,
    PRIMARY KEY (id_deteccao, moto_id_moto),
    FOREIGN KEY (moto_id_moto) REFERENCES moto(id_moto),
    FOREIGN KEY (camera_id_camera, camera_id_patio, camera_id_filial) 
        REFERENCES camera(id_camera, patio_id_patio, patio_id_filial)
);

-- Tabela Manutencao
CREATE TABLE manutencao (
    id_manutencao NUMBER(9),
    moto_id_moto NUMBER(9),
    data DATE NOT NULL,
    descricao CLOB NOT NULL,
    custo NUMBER(10,2) DEFAULT 0, -- Campo adicional para análise
    PRIMARY KEY (id_manutencao, moto_id_moto),
    FOREIGN KEY (moto_id_moto) REFERENCES moto(id_moto)
);

-- Tabela Usuario
CREATE TABLE usuario (
    id_usuario NUMBER(9),
    manutencao_id_manutencao NUMBER(9),
    manutencao_moto_id_moto NUMBER(9),
