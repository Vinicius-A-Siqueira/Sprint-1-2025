-- Tabela Filial
CREATE TABLE filial (
    id_filial NUMBER(9) PRIMARY KEY,
    nome VARCHAR2(100) NOT NULL,
    endereco VARCHAR2(200) NOT NULL
);

-- Tabela StatusMoto
CREATE TABLE statusmoto (
    id_status NUMBER(9) PRIMARY KEY,
    descricao VARCHAR2(50) NOT NULL
);

-- Tabela Patio
CREATE TABLE patio (
    id_patio NUMBER(9),
    filial_id_filial NUMBER(9),
    nome VARCHAR2(100) NOT NULL,
    localizacao VARCHAR2(200) NOT NULL,
    largura NUMBER(10,2) NOT NULL,
    comprimento NUMBER(10,2) NOT NULL,
    area_total NUMBER(10,2) NOT NULL,
    PRIMARY KEY (id_patio, filial_id_filial),
    FOREIGN KEY (filial_id_filial) REFERENCES filial(id_filial)
);

-- Tabela Camera
CREATE TABLE camera (
    id_camera NUMBER(9),
    patio_id_patio NUMBER(9),
    patio_id_filial NUMBER(9),
    localizacao VARCHAR2(200) NOT NULL,
    modelo VARCHAR2(100) NOT NULL,
    PRIMARY KEY (id_camera, patio_id_patio, patio_id_filial),
    FOREIGN KEY (patio_id_patio, patio_id_filial) REFERENCES patio(id_patio, filial_id_filial)
);

-- Tabela Leitura
CREATE TABLE leitura (
    id_leitura NUMBER(9) PRIMARY KEY,
    data_hora TIMESTAMP(0) NOT NULL
);

-- Tabela Moto
CREATE TABLE moto (
    id_moto NUMBER(9) PRIMARY KEY,
    placa VARCHAR2(10) UNIQUE NOT NULL,
    ano_fabricacao DATE NOT NULL,
    sensor_iot_id_sensor NUMBER(9),
    statusmoto_id_status NUMBER(9),
    patio_id_patio NUMBER(9),
    patio_filial_id_filial NUMBER(9),
    FOREIGN KEY (statusmoto_id_status) REFERENCES statusmoto(id_status),
    FOREIGN KEY (patio_id_patio, patio_filial_id_filial) REFERENCES patio(id_patio, filial_id_filial)
);

-- Tabela Sensor_IoT
CREATE TABLE sensor_iot (
    id_sensor NUMBER(9) PRIMARY KEY,
    tipo VARCHAR2(50) NOT NULL,
    fabricante VARCHAR2(100) NOT NULL,
    moto_id_moto NUMBER(9),
    FOREIGN KEY (moto_id_moto) REFERENCES moto(id_moto)
);

