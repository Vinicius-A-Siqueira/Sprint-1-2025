CREATE OR REPLACE TRIGGER tr_auditoria_moto
    AFTER INSERT OR UPDATE OR DELETE ON moto
    FOR EACH ROW
DECLARE
    v_operacao VARCHAR2(10);
    v_valores_antigos CLOB;
    v_valores_novos CLOB;
    v_usuario VARCHAR2(100);
BEGIN
    -- Determina o tipo de operação
    IF INSERTING THEN
        v_operacao := 'INSERT';
    ELSIF UPDATING THEN  
        v_operacao := 'UPDATE';
    ELSIF DELETING THEN
        v_operacao := 'DELETE';
    END IF;
    
    -- Captura o usuário atual
    SELECT USER INTO v_usuario FROM DUAL;
    
    -- Monta valores antigos (OLD)
    IF UPDATING OR DELETING THEN
        v_valores_antigos := 'id_moto:' || :OLD.id_moto || 
                           '|placa:' || :OLD.placa ||
                           '|ano_fabricacao:' || TO_CHAR(:OLD.ano_fabricacao, 'DD/MM/YYYY') ||
                           '|sensor_iot_id:' || :OLD.sensor_iot_id_sensor ||
                           '|status_id:' || :OLD.statusmoto_id_status ||
                           '|patio_id:' || :OLD.patio_id_patio ||
                           '|filial_id:' || :OLD.patio_filial_id_filial;
    END IF;
    
    -- Monta valores novos (NEW)
    IF INSERTING OR UPDATING THEN
        v_valores_novos := 'id_moto:' || :NEW.id_moto || 
                         '|placa:' || :NEW.placa ||
                         '|ano_fabricacao:' || TO_CHAR(:NEW.ano_fabricacao, 'DD/MM/YYYY') ||
                         '|sensor_iot_id:' || :NEW.sensor_iot_id_sensor ||
                         '|status_id:' || :NEW.statusmoto_id_status ||
                         '|patio_id:' || :NEW.patio_id_patio ||
                         '|filial_id:' || :NEW.patio_filial_id_filial;
    END IF;
    
    -- Insere registro na tabela de auditoria
    INSERT INTO auditoria (
        nome_usuario,
        tipo_operacao, 
        tabela_afetada,
        valores_antigos,
        valores_novos
    ) VALUES (
        v_usuario,
        v_operacao,
        'MOTO',
        v_valores_antigos,
        v_valores_novos
    );
    
EXCEPTION
    WHEN OTHERS THEN
        -- Em caso de erro na auditoria, registra erro mas não impede a operação principal
        INSERT INTO auditoria (
            nome_usuario,
            tipo_operacao,
            tabela_afetada, 
            valores_antigos,
            valores_novos
        ) VALUES (
            USER,
            'ERROR',
            'MOTO',
            'ERRO_TRIGGER: ' || SQLERRM,
            NULL
        );
END tr_auditoria_moto;
/

